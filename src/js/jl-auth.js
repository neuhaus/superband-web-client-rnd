/**
 * Conditional XOR/ADD mixing.
 * phase=3: bit set → XOR, clear → ADD.
 * phase=5: bit set → ADD, clear → XOR.
 */
function condMix(state, keyBlock, mask, phase) {
  const result = state.slice();
  for (let i = 0; i < 16; i++) {
    const bitSet = ((1 << i) & mask) !== 0;
    if (phase === 3) {
      result[i] = bitSet ? result[i] ^ keyBlock[i] : (keyBlock[i] + result[i]) & 0xff;
    } else {
      result[i] = bitSet ? (keyBlock[i] + result[i]) & 0xff : result[i] ^ keyBlock[i];
    }
  }
  return result;
}

/** Mixed SBOX/ISBOX substitution. */
function sboxSub(state) {
  const r = state.slice();
  for (const pos of [0, 3, 4, 7, 8, 11, 12, 15]) r[pos] = SBOX[r[pos]];
  for (const pos of [1, 2, 5, 6, 9, 10, 13, 14]) r[pos] = ISBOX[r[pos]];
  return r;
}

function blockCipher(state, ek, mode) {
  const initial = state.slice();
  let s = state.slice();

  s = condMix(s, ek.slice(0, 16), MASK, 3);
  s = sboxSub(s);
  s = condMix(s, ek.slice(16, 32), MASK, 5);

  for (let x9 = 1; x9 <= 8; x9++) {
    s = fibonacciMix(s);
    const ekOff = x9 * 0x20;

    if (x9 === 8) {
      s = condMix(s, ek.slice(0x100, 0x110), MASK, 3);
      break;
    }

    if (mode !== 0 && x9 === 2) {
      for (let i = 0; i < 16; i++) {
        const bitSet = ((1 << i) & MASK) !== 0;
        s[i] = bitSet ? s[i] ^ initial[i] : (initial[i] + s[i]) & 0xff;
      }
    }

    s = condMix(s, ek.slice(ekOff, ekOff + 16), MASK, 3);
    s = sboxSub(s);
    s = condMix(s, ek.slice(ekOff + 16, ekOff + 32), MASK, 5);
  }

  for (let i = 0; i < 16; i++) state[i] = s[i];
  return state;
}

function functionE1Test(key6, input16, seed16) {
  const expandedKey = new Array(16);
  for (let i = 0; i < 16; i++) expandedKey[i] = key6[i % 6];

  const output = input16.slice();
  const ks = keySchedule(seed16);
  blockCipher(output, ks, 0);

  for (let i = 0; i < 16; i++) output[i] = (expandedKey[i] + (output[i] ^ input16[i])) & 0xff;

  const obf = new Array(16);
  obf[0] = (seed16[0] - 0x17) & 0xff;
  obf[1] = (seed16[1] ^ 0xe5) & 0xff;
  obf[2] = (seed16[2] - 0x21) & 0xff;
  obf[3] = (seed16[3] ^ 0xc1) & 0xff;
  obf[4] = (seed16[4] - 0x4d) & 0xff;
  obf[5] = (seed16[5] ^ 0xa7) & 0xff;
  obf[6] = (seed16[6] - 0x6b) & 0xff;
  obf[7] = (seed16[7] ^ 0x83) & 0xff;
  obf[8] = (seed16[8] ^ 0xe9) & 0xff;
  obf[9] = (seed16[9] - 0x1b) & 0xff;
  obf[10] = (seed16[10] ^ 0xdf) & 0xff;
  obf[11] = (seed16[11] - 0x3f) & 0xff;
  obf[12] = (seed16[12] ^ 0xb3) & 0xff;
  obf[13] = (seed16[13] - 0x59) & 0xff;
  obf[14] = (seed16[14] ^ 0x95) & 0xff;
  obf[15] = (seed16[15] - 0x7d) & 0xff;

  const ks2 = keySchedule(obf);
  blockCipher(output, ks2, 1);
  return output;
}

/**
 * JieLi block cipher — encrypt a 16-byte block (key hardcoded in the firmware).
 * @param {Uint8Array} plaintext exactly 16 bytes
 * @returns {Uint8Array} 16 bytes
 */
export function jliEncrypt(plaintext) {
  if (!plaintext || plaintext.length !== BLOCK_SIZE) {
    throw new Error(`jliEncrypt: input must be ${BLOCK_SIZE} bytes, got ${plaintext?.length}`);
  }
  const out = functionE1Test(MAGIC, Array.from(plaintext), Array.from(STATIC_KEY));
  return Uint8Array.from(out);
}

/** 16 random bytes — the phone's challenge for auth step 1. */
export function randomAuthData() {
  const b = new Uint8Array(16);
  if (globalThis.crypto?.getRandomValues) globalThis.crypto.getRandomValues(b);
  else for (let i = 0; i < 16; i++) b[i] = Math.floor(Math.random() * 256);
  return b;
}

