/**
 * JieLi RCSP authentication cipher (service AE00).
 *
 * Port of qix-ble `qix_ble/auth.py` (itself a byte-for-byte port of
 * hybridherbst/web-bluetooth-e87 `jl_auth_v3.py`, verified against the ARM64
 * disassembly of `libjl_auth.so`). The badge refuses most RCSP commands until
 * the 6-step handshake below completes.
 *
 * The handshake is RAW over AE01/AE02 — NOT wrapped in the FE-DC-BA RCSP frame:
 *   step 1 (phone→dev): 00 ‖ 16B random
 *   step 2 (dev→phone): 01 ‖ encrypt(random)
 *   step 3 (phone→dev): 02 70 61 73 73   ("\x02pass")
 *   step 4 (dev→phone): 00 ‖ 16B challenge
 *   step 5 (phone→dev): 01 ‖ encrypt(challenge)
 *   step 6 (dev→phone): 02 70 61 73 73
 */

