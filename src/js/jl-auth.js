function keySchedule(data16) {
  const out = new Uint8Array(272);
  for (let i = 0; i < 16; i++) out[i] = data16[i];

  const buf = new Uint8Array(17);
  let checksum = 0;
  for (let i = 0; i < 16; i++) {
    buf[i] = data16[i];
    checksum ^= data16[i];
  }
  buf[16] = checksum & 0xff;

  for (let rnd = 0; rnd < 16; rnd++) {
    for (let i = 0; i < 17; i++) {
      const b = buf[i];
      buf[i] = ((b << 3) | (b >> 5)) & 0xff;
    }
    let readPos = (rnd + 1) % 17;
    for (let j = 0; j < 16; j++) {
      const src = buf[readPos];
      const tblIdx = 0xf + rnd * 16 - j;
      out[16 + rnd * 16 + j] = (KS_TABLE[tblIdx] + src) & 0xff;
      readPos += 1;
      if (readPos > 16) readPos = 0;
    }
  }
  return out;
}

